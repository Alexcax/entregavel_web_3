
 // Declara uma variável do tipo string (texto)
const nome = "Alexsander";

// Declara uma variável do tipo number (número)
const idade = 18;

// Declara uma variável do tipo boolean (verdadeiro ou falso)
const estudante = true;

// Declara uma variável sem atribuir um valor
let endereco;

// Declara uma variável com valor nulo
const telefone = null;

// Exibe o tipo de cada variável no console
console.log("Tipo de nome:", typeof nome);
console.log("Tipo de idade:", typeof idade);
console.log("Tipo de estudante:", typeof estudante);
console.log("Tipo de endereco:", typeof endereco);
console.log("Tipo de telefone:", typeof telefone);
