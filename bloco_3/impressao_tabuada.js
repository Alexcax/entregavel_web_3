
 // Declara uma constante com o número da tabuada
const numero = 5;

// Utiliza o laço for para repetir de 1 até 10
for (let i = 1; i <= 10; i++) {
    // Multiplica o número pelo contador
    const resultado = numero * i;

    // Exibe o resultado da multiplicação no console
    console.log(`${numero} x ${i} = ${resultado}`);
}
